/* ---- 回合控制器 ---- */
class Controller {
  constructor(cultivators) {
    this.cultivators = cultivators;
    this.effects = cultivators.map(() => []);
    this.environment = [];
    this.status = cultivators.map(() => 0);
    this.regenMP = cultivators.map(() => 0);   // 这回合开始时自然回复的真气量，空炸弹要把它撤销
    this.skipAgi = cultivators.map(() => 0);   // 这回合跳过的人：>0=跳过的闪避用这个敏捷(付不起时是原来的)，0=没跳过
    this.logs = []; this.mark = 0;
  }
  getNews() { const news = this.logs.slice(this.mark); this.mark = this.logs.length; return news; }
  rand() { return Math.random(); }

  startTurn() {
    this.status.fill(0);
    this.skipAgi.fill(0);
    this.execEffect(STAGE_START);
    for (let i = 0; i < this.cultivators.length; i++) { const before = this.cultivators[i].currentMP; this.recoverMP(i, -1); this.regenMP[i] = this.cultivators[i].currentMP - before; this.cultivators[i].recoverAgi(); }
  }

  actionTurn(actions) {
    this.execEffect(STAGE_ACTION);
    for (let i = 0; i < this.cultivators.length; i++) {
      const act = actions[i][0], target = actions[i][1];
      if (act.type === A_SKIP) { this.skipMove(i); this.paySkip(i); }
      else if (act.type === A_ACCUMULATE) {
        this.makeMove(i, target, act.point, act.text, act.power);
        this.cultivators[i].accumulatePower();
        this.cultivators[i].skipStreak = 0;
      }
      else if (this.status[i] & 1) { this.skipMove(i); this.paySkip(i); }
      else if (act.type === A_BOMB && this.cultivators[i].bomb <= 0) {
        this.skipMove(i);   // 空炸弹：纯跳过，不翻倍敏捷、不损失敏捷，闪避照常用自己的敏捷；这回合不回复真气
        this.cultivators[i].currentMP = Math.max(0, this.cultivators[i].currentMP - this.regenMP[i]);
      }
      else if (act.type === A_BOMB) {
        const bombPower = this.cultivators[i].bombPower();   // 战报里写明这次释放的炸弹能量
        this.makeMove(i, target, act.point, act.text + "(能量" + bombPower + ")", act.power);
        act.power = bombPower;
        this.cultivators[i].skipStreak = 0;
      }
      else {
        this.cultivators[i].skipStreak = 0;
        this.makeMove(i, target, act.point, act.text, act.power);
        const dot = getEffect(act, E_DOT);
        if (dot && !dot.needHit) {
          const amount = dot.instant;
          this.logs.push(logEffectAmount(i, target, amount, E_DOT));
          this.takeDamage(i, target, act.effects, actions[target][0].effects, act.attr, amount, true, actions[target][0].attr);
          this.addEffect(target, cloneEffect(dot));
        }
        for (const [type, apply, log] of [
          [E_REBATE, a => this.recoverMP(i, a), E_REBATE],
          [E_RECOVER, a => this.recoverATK(i, a), E_RECOVER],
          [E_CURE, a => this.recoverHP(i, a), E_CURE]]) {
          const eff = getEffect(act, type);
          if (eff && !eff.needHit) {
            this.logs.push(logEffectAmount(i, -1, eff.instant, log));
            apply(eff.instant);
            this.addEffect(i, cloneEffect(eff));
          }
        }
      }
    }
    for (const [action] of actions) this.putoutReaction(action.attr);
  }

  checkTurn(actions) {
    this.execEffect(STAGE_CHECK);
    const rust = () => this.findReaction(E_RUST);
    // 被禁锢的一方这回合出的招(除了积攒)已经被跳过，它的减伤/反弹/吸收/物理等效果也不能生效，当作跳过处理
    actions = actions.map((a, j) => ((this.status[j] & 1) && a[0].type !== A_ACCUMULATE) ? [skipAction(), a[1]]
      : (a[0].type === A_BOMB && a[0].power <= 0) ? [skipAction(), a[1]] : a);   // 空炸弹只是纯跳过
    for (let i = 0; i < this.cultivators.length; i++) {
      const actI = actions[i][0], targetI = actions[i][1];
      if (actI.type === A_SKIP || actI.type === A_ACCUMULATE) continue;
      if (this.status[i] & 1) continue;
      const j = targetI;
      const actJ = actions[j][0];
      const ci = this.cultivators[i], cj = this.cultivators[j];
      const notFaced = actJ.type === A_SKIP || actJ.type === A_ACCUMULATE || actions[j][1] !== i || (this.status[j] & 1);

      if (actI.type === A_BOMB) {
        if (notFaced) {
          const powerEnemy = actI.power * (rust() ? BOMB_RUST_FACTOR : BOMB_HIT_FACTOR_PASSIVE);
          const powerSelf = actI.power * (rust() ? BOMB_RUST_FACTOR : BOMB_BACKFIRE_FACTOR);
          this.takeDamage(i, j, actI.effects, actJ.effects, actI.attr, Math.trunc(powerEnemy), true, actJ.attr);
          this.takeDamage(i, i, actI.effects, actI.effects, actI.attr, Math.trunc(powerSelf));
        }
        else if (actJ.type === A_BOMB && actions[j][1] === i) {
          const sum = actI.power + actJ.power;   // 互扔炸弹：两个炸弹之和乘反噬系数，双方一起受到
          const powerEnemy = sum * (rust() ? BOMB_RUST_FACTOR : BOMB_BACKFIRE_FACTOR);
          this.takeDamage(j, j, actJ.effects, actJ.effects, actJ.attr, Math.trunc(powerEnemy));
        }
        else if (actJ.power < actI.power) {
          let powerEnemy = actI.power - actJ.power;
          powerEnemy *= (rust() ? BOMB_RUST_FACTOR : BOMB_HIT_FACTOR_ACTIVE);
          this.takeDamage(i, j, actI.effects, actJ.effects, actI.attr, Math.trunc(powerEnemy), true, actJ.attr);
        }
        continue;
      }

      // 玩家 i 施放普通招式
      if (notFaced) {
        // 对方跳过(含被禁锢而无法出招，但没有选积攒)时：付得起敏捷损失就用翻倍的敏捷闪避(被禁锢的一方也能)，
        // 付不起(闪避之后敏捷会低于1)就无法闪避；没跳过的一方照常用自己的敏捷闪避，被禁锢时不能闪避
        let defAgi = cj.agi, canDodge = true;   // 被禁锢又选了积攒的人也用自己当前的敏捷闪避
        if (this.skipAgi[j] > 0) { defAgi = this.skipAgi[j]; canDodge = true; }
        const dodgeChance = rust() ? 0 : (defAgi * defAgi) / (ci.agi * ci.agi + defAgi * defAgi);
        if (canDodge && this.rand() < dodgeChance) { this.dodgeSuccess(i, j); this.buildDualEnvironment(actI); continue; }   // 双招被闪避=未命中，计入场地效果
        let hit = true;
        if (this.findReaction(E_DUST)) hit = this.rand() < 0.5;
        if (hit) {
          this.hitSuccess(i, j, actI, actJ);
          this.takeDamage(i, j, actI.effects, actJ.effects, actI.attr, actI.power, true, actJ.attr);
        } else { this.hitFail(i); this.buildDualEnvironment(actI); }
      }
      else if (actJ.type === A_BOMB && actions[j][1] === i) {
        // 目标 j 施放真气炸弹且指向 i：只计算 j 受到的伤害
        let powerEnemy = 0;
        if (actI.power < actJ.power) {
          powerEnemy = actJ.power * (rust() ? BOMB_RUST_FACTOR : BOMB_BACKFIRE_FACTOR);
          this.takeDamage(j, j, actJ.effects, actJ.effects, actJ.attr, Math.trunc(powerEnemy));
        }
        else if (actI.power > 2 * actJ.power) {
          powerEnemy = actI.power - 2 * actJ.power;
          this.takeDamage(i, j, actI.effects, actJ.effects, actI.attr, Math.trunc(powerEnemy), true, actJ.attr);
        }
        else {
          powerEnemy = 2 * actJ.power - actI.power;
          powerEnemy *= (rust() ? BOMB_RUST_FACTOR : BOMB_BACKFIRE_FACTOR);
          this.takeDamage(j, j, actJ.effects, actJ.effects, actJ.attr, Math.trunc(powerEnemy));
        }
      }
      else {
        // 双方互相施放普通招式，每对只算一次
        if (j < i) continue;
        let point1 = actI.power, point2 = actJ.power;
        const attr1 = actI.attr, attr2 = actJ.attr;
        if (this.checkCounter(attr1, attr2)) point2 = Math.trunc(point2 / 2);
        if (this.checkCounter(attr2, attr1)) point1 = Math.trunc(point1 / 2);

        // 双方出招的最终属性碰撞产生的场地效果；双招自己的两个基础招式构造的场地效果只在双招未命中时才产生
        const clashReaction = this.addReaction(this.checkReaction(attr1, attr2));

        const dust = this.findReaction(E_DUST);
        const hit = dust ? this.rand() < 0.5 : true;
        if (!hit) {
          this.hitFail(i);
          if (!clashReaction) { this.buildDualEnvironment(actI); this.buildDualEnvironment(actJ); }
          continue;
        }

        // 穿透：额外伤害按较小的那一个威力算(平局时各按对方的)
        const penetrate = (pointForI, pointForJ) => {
          let eff = getEffect(actI, E_PENETRATE);
          if (eff) {
            const pen = Math.trunc(pointForI * ratioOf(eff, attr2));
            this.logs.push(logEffectDamage(i, j, attr1, pen, 0, E_PENETRATE));
            this.takeDamage(i, j, actI.effects, actJ.effects, attr1, pen, false, attr2);
          }
          eff = getEffect(actJ, E_PENETRATE);
          if (eff) {
            const pen = Math.trunc(pointForJ * ratioOf(eff, attr1));
            this.logs.push(logEffectDamage(j, i, attr2, pen, 0, E_PENETRATE));
            this.takeDamage(j, i, actJ.effects, actI.effects, attr2, pen, false, attr1);
          }
        };
        if (point1 > point2) {
          this.hitSuccess(i, j, actI, actJ); this.hitSuccess(j, i, actJ, actI);
          this.takeDamage(i, j, actI.effects, actJ.effects, attr1, point1 - point2, true, attr2);
          penetrate(point2, point2);
        }
        else if (point2 > point1) {
          this.hitSuccess(i, j, actI, actJ); this.hitSuccess(j, i, actJ, actI);
          this.takeDamage(j, i, actJ.effects, actI.effects, attr2, point2 - point1, true, attr1);
          penetrate(point1, point1);
        }
        else {
          this.hitSuccess(i, j, actI, actJ); this.hitSuccess(j, i, actJ, actI);
          penetrate(point2, point1);
        }
      }
    }
  }

  endTurn() {
    this.execEffect(STAGE_END);
    this.environment = this.environment.filter(e => { e.currentRound++; return e.currentRound < e.total; });
  }

  addEffect(idx, effect) { if (idx >= 0 && idx < this.effects.length) this.effects[idx].push(effect); }
  addEnvironment(effect) {
    const k = this.environment.findIndex(e => e.type === effect.type);
    if (k < 0) this.environment.push(effect); else this.environment[k] = effect;
  }

  execEffect(stage) {
    if (stage !== STAGE_START) return; // 所有持续效果都只在回合开始阶段结算
    for (let i = 0; i < this.effects.length; i++) {
      for (let j = 0; j < this.effects[i].length; j++) {
        const eff = this.effects[i][j];
        const erase = () => { this.effects[i].splice(j, 1); j--; };
        if (eff.type === E_LOCK) { this.status[i] |= 1; erase(); }
        else if (eff.type === E_DOT) {
          const dmg = timedOnce(eff);
          if (dmg !== 0) { this.logs.push(logEffectAmount(-1, i, dmg, E_DOT)); this.takeDamage(-1, i, [], [], NONE, dmg, false); }
          if (timedUsedUp(eff)) erase();
        }
        else if (eff.type === E_REBATE) {
          const v = timedOnce(eff);
          if (v !== 0) { this.logs.push(logEffectAmount(i, -1, v, E_REBATE)); this.recoverMP(i, v, false); }
          if (timedUsedUp(eff)) erase();
        }
        else if (eff.type === E_RECOVER) {
          const v = timedOnce(eff);
          if (v !== 0) { this.logs.push(logEffectAmount(i, -1, v, E_RECOVER)); this.recoverATK(i, v, false); }
          if (timedUsedUp(eff)) erase();
        }
        else if (eff.type === E_CURE) {
          const v = timedOnce(eff);
          if (v !== 0) { this.logs.push(logEffectAmount(i, -1, v, E_CURE)); this.recoverHP(i, v, false); }
          if (timedUsedUp(eff)) erase();
        }
      }
    }
  }

  recoverMP(idx, amount, log = true) { if (log) this.logs.push(logState(L_MP, idx, amount)); this.cultivators[idx].recoverMP(amount); }
  makeMove(subject, object, amount, name, point) {
    if (this.findReaction(E_MUD)) amount = Math.trunc(amount * 1.5);
    this.logs.push(logMove(subject, object, amount, name, point));
    // 真气不够时先扣光真气，缺的部分按2倍从武力值里透支(consumeMP)，把透支扣掉的武力值写进战报
    const deficit = amount - this.cultivators[subject].currentMP;
    if (deficit > 0) this.logs.push(logState(L_CONSUME, subject, deficit * 2));
    this.cultivators[subject].consumeMP(amount);
  }
  addReaction(r) { if ([E_BURN, E_RUST, E_DUST, E_MUD].includes(r)) { this.addEnvironment(envEffect(r)); return true; } return false; }
  buildDualEnvironment(act) { if (act.type === A_DUAL) this.addReaction(this.checkReaction(act.action1.attr, act.action2.attr)); }
  skipMove(idx) { this.logs.push(logSkip(idx)); }
  recoverATK(idx, amount, log = true) { if (log) this.logs.push(logState(L_ATK, idx, amount)); this.cultivators[idx].recoverATK(amount); }
  recoverHP(idx, amount, log = true) { if (log) this.logs.push(logState(L_HP, idx, amount)); this.cultivators[idx].recoverHP(amount); }
  hitFail(subject) { this.logs.push(logState(L_FAIL, subject, 0)); }
  dodgeSuccess(subject, object) { this.logs.push(logDodge(subject, object)); }

  // 跳过一次的敏捷损失：付得起(之后不低于1)就记下翻倍后的闪避敏捷，付不起就标记这回合没有闪避
  paySkip(i) {
    const c = this.cultivators[i];
    if (c.canDodge()) { this.skipAgi[i] = c.agi * SKIP_AGI_FACTOR; c.consumeAgi(); }
    else this.skipAgi[i] = c.agi;   // 付不起：不翻倍、不扣敏捷，仍用原来的敏捷闪避
  }

  hitSuccess(subject, object, offend, defend) {
    const lock = getEffect(offend, E_LOCK);
    if (lock) {
      if (this.rand() < lock.prob) { this.logs.push(logEffectAmount(subject, object, 0, E_LOCK)); this.addEffect(object, lock); }
      else lock.keep = false;
    }
    const dot = getEffect(offend, E_DOT);
    if (dot && dot.needHit) {
      this.logs.push(logEffectAmount(subject, object, dot.instant, E_DOT));
      this.takeDamage(subject, object, offend.effects, defend.effects, offend.attr, dot.instant, true, defend.attr);
      this.addEffect(object, cloneEffect(dot));
    }
    for (const [type, apply] of [
      [E_REBATE, a => this.recoverMP(subject, a)], [E_RECOVER, a => this.recoverATK(subject, a)], [E_CURE, a => this.recoverHP(subject, a)]]) {
      const eff = getEffect(offend, type);
      if (eff && eff.needHit) {
        this.logs.push(logEffectAmount(subject, -1, eff.instant, type));
        apply(eff.instant);
        this.addEffect(subject, cloneEffect(eff));
      }
    }
  }

  // 伤害(amount)：先减伤，再按物理比例拆成武力伤害/物理伤害，反弹、吸收
  takeDamage(subject, object, offend, defend, attribute, amount, log = true, defendAttribute = NONE) {
    if (this.findReaction(E_BURN)) amount = Math.trunc(amount * 1.5);
    const reduce = defend.find(e => e.type === E_REDUCE);
    if (reduce) amount = Math.trunc(amount * (1 - ratioOf(reduce, attribute)));

    let physicalRatio = 0;
    const physical = offend.find(e => e.type === E_PHYSICAL);
    if (physical) physicalRatio = Math.min(1, Math.max(0, ratioOf(physical, defendAttribute)));
    const hpPart = Math.trunc(amount * physicalRatio);
    const atkPart = amount - hpPart;

    // 反弹是减伤的升级版：受击者只承受反弹之后剩下的伤害，被反弹的那部分全部还给攻击者
    let reboundAtk = 0, reboundHp = 0;
    if (subject !== object) {
      const rebound = defend.find(e => e.type === E_REBOUND);
      if (rebound) {
        const ratio = Math.min(1, Math.max(0, ratioOf(rebound, attribute)));
        reboundAtk = Math.trunc(atkPart * ratio); reboundHp = Math.trunc(hpPart * ratio);
      }
    }
    const ownAtk = atkPart - reboundAtk, ownHp = hpPart - reboundHp;

    if (log) this.logs.push(logDamage(subject, object, attribute, ownAtk, ownHp));
    if (ownAtk > 0) this.cultivators[object].takeDamage(ownAtk, false);
    if (ownHp > 0) this.cultivators[object].takeDamage(ownHp, true);

    if (subject === object) return;

    if (reboundAtk > 0 || reboundHp > 0) {
      this.logs.push(logEffectDamage(object, subject, attribute, reboundAtk, reboundHp, E_REBOUND));
      this.takeDamageSplit(object, subject, defend, offend, attribute, reboundAtk, reboundHp, false);
    }
    const absorb = defend.find(e => e.type === E_ABSORB);
    if (absorb) {
      const mp = Math.trunc(amount * ratioOf(absorb, attribute));
      this.logs.push(logEffectAmount(object, subject, mp, E_ABSORB));
      this.recoverMP(object, mp);
    }
  }

  // 伤害(武力值部分atk、物理部分hp)：反弹回来的伤害走这个
  takeDamageSplit(subject, object, offend, defend, attribute, atk, hp, log = true, depth = 0) {
    // 反弹回来的伤害是从已经结算过(含灼烧加成)的伤害按比例算出来的，不再乘一次灼烧；并限制反弹的递归深度
    if (depth >= 8) return;
    const reduce = defend.find(e => e.type === E_REDUCE);
    if (reduce) { const keep = 1 - ratioOf(reduce, attribute); atk = Math.trunc(atk * keep); hp = Math.trunc(hp * keep); }

    let reboundAtk = 0, reboundHp = 0;
    if (subject !== object) {
      const rebound = defend.find(e => e.type === E_REBOUND);
      if (rebound) {
        const ratio = Math.min(1, Math.max(0, ratioOf(rebound, attribute)));
        reboundAtk = Math.trunc(atk * ratio); reboundHp = Math.trunc(hp * ratio);
      }
    }
    const ownAtk = atk - reboundAtk, ownHp = hp - reboundHp;
    if (log) this.logs.push(logDamage(subject, object, attribute, ownAtk, ownHp));
    if (ownAtk > 0) this.cultivators[object].takeDamage(ownAtk, false);
    if (ownHp > 0) this.cultivators[object].takeDamage(ownHp, true);

    if (subject === object) return;
    if (reboundAtk > 0 || reboundHp > 0) {
      this.logs.push(logEffectDamage(object, subject, attribute, reboundAtk, reboundHp, E_REBOUND));
      this.takeDamageSplit(object, subject, defend, offend, attribute, reboundAtk, reboundHp, false, depth + 1);
    }
    const absorb = defend.find(e => e.type === E_ABSORB);
    if (absorb) {
      const mp = Math.trunc((atk + hp) * ratioOf(absorb, attribute));
      this.logs.push(logEffectAmount(object, subject, mp, E_ABSORB));
      this.recoverMP(object, mp);
    }
  }

  checkCounter(a1, a2) { return COUNTERS.has(a1 + "," + a2); }
  checkReaction(a1, a2) {
    if (a1 === METAL) { if (a2 === FIRE) return E_BURN; if (a2 === WATER) return E_RUST; }
    if (a1 === EARTH) { if (a2 === FIRE) return E_DUST; if (a2 === WATER) return E_MUD; }
    if (a1 === FIRE) { if (a2 === METAL) return E_BURN; if (a2 === EARTH) return E_DUST; }
    if (a1 === WATER) { if (a2 === METAL) return E_RUST; if (a2 === EARTH) return E_MUD; }
    return E_NONE;
  }
  findReaction(type) { return this.environment.some(e => e.type === type); }
  putoutReaction(attribute) {
    const remove = types => { this.environment = this.environment.filter(e => !types.includes(e.type)); };
    if (attribute === METAL) remove([E_DUST, E_MUD]);
    else if (attribute === WATER) remove([E_BURN, E_DUST]);
    else if (attribute === FIRE) remove([E_RUST, E_MUD]);
    else if (attribute === EARTH) remove([E_BURN, E_RUST]);
  }
}

/* ---- 策略AI(表格式)，对应 battle/ai.cpp ---- */
class PolicyAI {
  constructor() { this.familyCount = 0; this.classProb = []; this.singleProb = []; this.dualProb = []; this.reset(); }
  load(text, count) {
    const t = text.split(/\s+/).filter(Boolean).map(Number);
    if (t.length === 0 || t[0] !== count) return false;
    let pos = 1;
    const take = n => { const row = t.slice(pos, pos + n); pos += n; return row.length === n && row.every(x => !Number.isNaN(x)) ? row : null; };
    const classProb = [], singleProb = [], dualProb = [];
    for (let i = 0; i < 324; i++) { const r = take(5); if (!r) return false; classProb.push(r); }
    for (let i = 0; i < 32; i++) { const r = take(count); if (!r) return false; singleProb.push(r); }
    for (let i = 0; i < 32; i++) { const r = take(count); if (!r) return false; dualProb.push(r); }
    this.familyCount = count; this.classProb = classProb; this.singleProb = singleProb; this.dualProb = dualProb;
    return true;
  }
  reset() { this.opponentAccumulate = 0; this.opponentAttribute = 7; }
  observe(action) {
    if (action.type === A_ACCUMULATE) this.opponentAccumulate++;
    else if (action.type === A_BOMB) this.opponentAccumulate = 0;
    this.opponentAttribute = (action.type === A_SINGLE || action.type === A_DUAL) ? action.attr : 7;
  }
  static mpBucket(c) { const r = c.currentMP / c.maxMP; return r < 0.088 ? 0 : r < 0.294 ? 1 : r < 0.588 ? 2 : 3; }
  static vitality(c) {
    const v = Math.min(c.currentHP / c.maxHP, c.currentATK / c.maxATK);
    return v > 0.66 ? 0 : v > 0.33 ? 1 : 2;
  }
  stateOf(me, opp) {
    const bomb = me.bomb <= 0 ? 0 : (me.bomb / me.maxMP <= 0.235 ? 1 : 2);
    return (((PolicyAI.mpBucket(me) * 3 + bomb) * 3 + PolicyAI.vitality(me)) * 3 + PolicyAI.vitality(opp)) * 3 + Math.min(this.opponentAccumulate, 2);
  }
  pick(weights) {
    let sum = 0; for (const w of weights) sum += w;
    let r = Math.random() * sum;
    for (let i = 0; i < weights.length; i++) { r -= weights[i]; if (r < 0) return i; }
    return weights.length - 1;
  }
  choose(me, opp, familyActions) {
    if (!this.classProb.length || familyActions.length !== this.familyCount) return skipAction();
    const cls = this.pick(this.classProb[this.stateOf(me, opp)]);
    const ctx = PolicyAI.mpBucket(me) * 8 + this.opponentAttribute;
    switch (cls) {
      case 0: return skipAction();
      case 1: return accumulateAction();
      case 2: return bombAction();
      case 3: return me.getAction(familyActions[this.pick(this.singleProb[ctx])]);
      default: {
        const first = this.pick(this.dualProb[ctx]), second = this.pick(this.dualProb[ctx]);
        return me.getAction(familyActions[first], familyActions[second]);
      }
    }
  }
}
