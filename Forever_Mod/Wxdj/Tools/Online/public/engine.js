class Cultivator {
  constructor(name, defs, hp, atk, mp, agi, recover, agiLoss = 1, agiRecover = 0.2, bombMultiplier = BOMB_ACCUMULATE_MULTIPLIER) {
    this.name = name; this.defs = defs;
    this.maxHP = this.currentHP = hp; this.maxATK = this.currentATK = atk; this.maxMP = this.currentMP = mp;
    // 敏捷：当前值agi，上限maxAgi；闪避一次损失agiLoss，每回合自动恢复agiRecover(不超过上限)
    this.agi = agi; this.maxAgi = agi; this.agiLoss = agiLoss; this.agiRecover = agiRecover; this.skipStreak = 0;
    this.recover = recover; this.bomb = 0; this.bombMultiplier = bombMultiplier;   // 炸弹积攒倍率：个人属性，由所在阶位决定
  }
  skipLoss() { return this.agiLoss + SKIP_STREAK_EXTRA_LOSS * this.skipStreak; }   // 这次跳过要扣多少敏捷
  canDodge() { return this.agi - this.skipLoss() >= 1 - 1e-4; }   // 跳过得起吗：跳过要损失agiLoss点敏捷，之后敏捷不能低于1
  consumeAgi() { this.agi = Math.max(1, this.agi - this.skipLoss()); this.skipStreak++; }
  recoverAgi() { this.agi = Math.min(this.maxAgi, this.agi + this.agiRecover); }
  isAlive() { return this.currentHP > 0 && this.currentATK > 0; }
  getAction(a, b) {
    const n = this.defs.length;
    if (typeof a === "string") {
      if (b === undefined) { const d = this.defs.find(x => x.name === a); return d ? singleFromDef(d) : skipAction(); }
      const d1 = this.defs.find(x => x.name === a), d2 = this.defs.find(x => x.name === b);
      if (d1 && d2) { const s1 = singleFromDef(d1), s2 = singleFromDef(d2); if (sameForm(s1, s2)) return dualAction(s1, s2); }
      return skipAction();
    }
    if (b === undefined) {
      // 0..n-1 单招，n..n+2 积攒，n+3 炸弹，其余跳过
      if (a < 0 || a >= n + 4) return skipAction();
      if (a >= n && a <= n + 2) return accumulateAction();
      if (a === n + 3) return bombAction();
      return singleFromDef(this.defs[a]);
    }
    if (a < 0 || a >= n || b < 0 || b >= n) return skipAction();
    const s1 = singleFromDef(this.defs[a]), s2 = singleFromDef(this.defs[b]);
    return sameForm(s1, s2) ? dualAction(s1, s2) : skipAction();
  }
  recoverMP(amount) {
    this.currentMP += amount <= 0 ? this.recover : amount;
    if (this.currentMP > this.maxMP * 2) this.currentHP = 0;
    else if (this.currentMP > this.maxMP) this.currentMP = this.maxMP;
  }
  consumeMP(amount) {
    if (this.currentMP >= amount) this.currentMP -= amount;
    else { const deficit = amount - this.currentMP; this.currentMP = 0; this.currentATK = Math.max(0, this.currentATK - deficit * 2); }
  }
  recoverATK(amount) { this.currentATK = Math.min(this.maxATK, this.currentATK + amount); }
  recoverHP(amount) { this.currentHP = Math.min(this.maxHP, this.currentHP + amount); }
  takeDamage(amount, physical) {
    if (physical) this.currentHP = Math.max(0, this.currentHP - amount);
    else {
      if (amount >= this.currentATK * 0.6) this.currentHP = Math.max(0, this.currentHP - amount);
      else if (amount >= this.currentATK * 0.3) this.currentHP = Math.max(0, Math.trunc(this.currentHP - amount * 0.5));
      this.currentATK -= amount;
    }
  }
  accumulatePower() {
    // 消耗当前真气的一部分，按倍数存进炸弹
    const spent = Math.trunc(ACCUMULATE_FRACTION * this.currentMP);
    this.currentMP -= spent;
    this.bomb += Math.trunc(spent * this.bombMultiplier);
  }
  bombPower() { const p = this.bomb; this.bomb = 0; return p; }
}

