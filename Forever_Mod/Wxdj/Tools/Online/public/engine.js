function ratioEffect(type, r) {
  const ratios = [0, 0, 0, 0, 0, 0, 0];
  for (let i = 0; i < 7; i++) if (r[i] > 0) ratios[i] = r[i];
  return { type, ratios };
}
function physicalAll() { return { type: E_PHYSICAL, ratios: [1, 1, 1, 1, 1, 1, 1] }; }
function timedEffect(type, instant, continuous = 0, rounds = 0, interval = 1) {
  return { type, instant, continuous, rounds, interval, needHit: type === E_DOT, currentRound: 0 };
}
function lockEffect(prob) { return { type: E_LOCK, prob, keep: true }; }
function envEffect(type) { return { type, total: 3, currentRound: 0 }; }
function cloneEffect(e) { return Object.assign({}, e, e.ratios ? { ratios: e.ratios.slice() } : {}); }
function ratioOf(e, attr) { return e.ratios[attr] || 0; }
function timedOnce(e) {
  e.currentRound++;
  if (e.currentRound >= e.interval && e.rounds > 0) { e.rounds--; e.currentRound = 0; return e.continuous; }
  return 0;
}
const timedUsedUp = e => e.rounds <= 0;

function parseEffect(line) {
  const t = line.trim().split(/\s+/);
  const kind = t[0];
  const nums = t.slice(1).map(Number);
  const has = n => nums.length >= n && nums.slice(0, n).every(x => !Number.isNaN(x));
  switch (kind) {
    case "physical": return has(7) ? ratioEffect(E_PHYSICAL, nums) : physicalAll();
    case "penetrate": return has(7) ? ratioEffect(E_PENETRATE, nums) : null;
    case "reduce": return has(7) ? ratioEffect(E_REDUCE, nums) : null;
    case "rebound": return has(7) ? ratioEffect(E_REBOUND, nums) : null;
    case "absorb": return has(7) ? ratioEffect(E_ABSORB, nums) : null;
    case "lock": return has(1) ? lockEffect(nums[0]) : null;
    case "dot": case "rebate": case "recover": case "cure": {
      // 和原版解析一致：必须给全4个数(instant continuous rounds interval)
      if (!has(4)) return null;
      const type = { dot: E_DOT, rebate: E_REBATE, recover: E_RECOVER, cure: E_CURE }[kind];
      return timedEffect(type, nums[0] | 0, nums[1] | 0, nums[2] | 0, nums[3] | 0);
    }
  }
  return null;
}

