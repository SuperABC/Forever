function makeAction(type, attr, point, power, effects, text) { return { type, attr, point, power, effects, text }; }
const skipAction = () => makeAction(A_SKIP, NONE, 0, 0, [], "无");
const accumulateAction = () => makeAction(A_ACCUMULATE, NONE, 0, 0, [], "积攒真气炸弹");
const bombAction = () => makeAction(A_BOMB, NONE, 0, 0, [physicalAll()], "释放真气炸弹");
function singleFromDef(def) {
  const a = makeAction(A_SINGLE, def.attr, def.point, def.power, def.effects.map(cloneEffect), def.name);
  a.name = def.name;
  return a;
}
function dualAction(a1, a2) {
  const attr = DUAL_PRIMARY[a1.attr + "," + a2.attr];
  const a = makeAction(A_DUAL, attr,
    Math.trunc(DUAL_COST_FACTOR * (a1.point + a2.point)), Math.trunc(DUAL_POWER_FACTOR * (a1.power + a2.power)),
    a1.effects.concat(a2.effects.filter(e => !a1.effects.some(o => o.type === e.type))),   // 同名效果只取第一个招式的
    "(" + a1.name + ", " + a2.name + ")");
  a.action1 = a1; a.action2 = a2;
  return a;
}
function getEffect(action, type) { return action.effects.find(e => e.type === type) || null; }

// 双招的两招必须同式：招式名是"家族名+第X式"，比较"第X式"部分
function sameForm(a, b) {
  const p1 = a.name.indexOf("第"), p2 = b.name.indexOf("第");
  if (p1 < 0 || p2 < 0) return true;
  return a.name.slice(p1) === b.name.slice(p2);
}

function parseActions(text) {
  const lines = text.replace(/\r/g, "").split("\n");
  const defs = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line === "" || line[0] === "#") continue;
    const t = line.trim().split(/\s+/);
    if (t.length < 6) continue;
    const mp = parseInt(t[2]), atk = parseInt(t[3]), count = parseInt(t[5]);
    if ([mp, atk, count].some(Number.isNaN)) continue;
    const effects = [];
    for (let k = 0; k < count; k++) {
      i++;
      if (i >= lines.length) break;
      const e = parseEffect(lines[i]);
      if (e) effects.push(e);
    }
    defs.push({ name: t[0], attr: ATTR_PARSE[t[1]] ?? NONE, point: mp, power: atk, realm: t[4], effects });
  }
  return defs;
}

